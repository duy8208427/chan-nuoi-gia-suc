function clock(offsetMin: number): string {
  const date = new Date(Date.now() + offsetMin * 60_000);
  const pad = (value: number) => String(value).padStart(2, "0");
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

function judge(stage: HerdStage, code: string, value: number): AlertStatus {
  const band = BANDS[stage]?.[code];
  if (!band) return "OK";
  if (band.ref_min != null && value < band.ref_min) return "LOW";
  if (band.ref_max != null && value > band.ref_max) return "HIGH";
  return "OK";
}

function measures(stage: HerdStage, overrides: Record<string, number> = {}, at = AT): Measurement[] {
  return Object.entries(DEFAULTS[stage]).map(([param_code, base]) => {
    const measured_value = overrides[param_code] ?? base;
    return {
      param_code,
      measured_value,
      unit: UNITS[param_code] ?? "",
      measured_at: at,
      status: judge(stage, param_code, measured_value),
    };
  });
}

function pond(input: Omit<Pond, "sample" | "created_at"> & { created_at?: string }): Pond {
  return { sample: true, created_at: input.created_at ?? "2026-03-12 07:00:00", ...input };
}

function asset(
  pond_id: string,
  kind: AssetKind,
  name: string,
  location_label: string,
  status: AssetStatus,
  extra: Partial<Asset> = {},
): Asset {
  return {
    id: extra.id ?? `${pond_id}-${kind}-${location_label}`,
    pond_id,
    kind,
    name,
    location_label,
    status,
    last_seen: extra.last_seen ?? AT,
    device_code: extra.device_code,
  };
}

